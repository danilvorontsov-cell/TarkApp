def build_tutor_user_prompt(profile: UserProfile) -> str:
    """Constructs the user prompt guiding Gemini to classify and analyze the image."""
    tier = profile.tier or AgeTier.from_grade(profile.grade)
    nickname_label = profile.nickname or "Друг"

    tier_descriptions = {
        AgeTier.PRIMARY: "Младшие классы (1–3 класс, Algkool). Очень теплый, добрый тон, простые слова, игровые метафоры (Minecraft, LEGO, питомцы), интерактивный шаблон со слотами [слово].",
        AgeTier.MIDDLE: "Средние классы (4–6 класс, Põhikool I). Структурированный понятный разбор, аналогии через спорт, гаджеты и интересы, интерактивный шаблон со слотами [слово].",
        AgeTier.HIGH: "Старшие классы (7–9 класс, Põhikool II). Строгая логика и четкая структура БЕЗ детских метафор, упор на формулы, терминологию, алгоритмы и шаги доказательства.",
        AgeTier.GYMNASIUM: "Гимназия (10–12 класс, Gümnaasium). Академический стиль конспекта, тезисный разбор, акцент на подготовку к государственным экзаменам (riigieksamid). Готовый академический образец формулировки (Näidissõnastus) без игровых слотов.",
    }

    tier_label = tier_descriptions.get(tier, "Среднее звено")

    user_interests_str = (
        ", ".join(profile.interests) if profile.interests else "не указаны (выбери из общевозрастного пула)"
    )

    fallback_pool = AGE_TIER_DEFAULT_INTERESTS.get(tier, [])
    fallback_pool_str = ", ".join(fallback_pool)

    return f"""Проанализируй прикрепленное изображение и адаптируй ответ для ученика.

ШАГ 1: КЛАССИФИКАЦИЯ
Определи, что находится на изображении:
- РЕЖИМ A (Õppetöö): учебник, рабочая тетрадь, задание, экран eKool/Opiq или рукописный пример.
- РЕЖИМ B (Maailma Avastaja): реальный предмет окружающего мира, бытовой объект, животное, еда, игрушка, комната, природа, растение или улица.

ШАГ 2: ВЫПОЛНЕНИЕ РАЗБОРА
Примени регламент соответствующего режима (Режим A или Режим B) согласно системному промпту.
- РАЗМЕТКА ОЗВУЧКИ (TTS):
  * Все эстонские термины в русском тексте пиши в скобках после русского слова: русское слово (<est>эстонский термин</est>), например: клавиатура (<est>klaviatuur</est>), кнопка (<est>klahv</est>). Никогда не заменяй русские слова голым эстонским термином!
  * Любые эстонские вопросы/фразы в условии (worked_example.given) и шагах (worked_example.steps) оборачивай в <est>фраза</est>, например: Учитель спрашивает: <est>Mis seade see on?</est>.
  * Английские бренды и названия в русском тексте (Minecraft, Roblox, YouTube, клавиши W/A/S/D) оставляй латиницей БЕЗ тегов.
Если это Режим A (Школьное задание):
- Соблюдай анти-чит политику (NO-LEAK): не пиши готовые ответы к конкретным номерам, используй в worked_example вымышленные числа, объясни метод решения и переведи термины.
Если это Режим B (Исследователь мира):
- task_title СТРОГО в формате "Avastus: [Эстонское название] ([Русский перевод])"
- theme_explanation свяжи с увлечением ученика и его возрастом
- vocabulary: 3-4 ключевых эстонских слова (существительное, прилагательное, глагол)
- how_to_answer: как рассказать об объекте на уроке в эстонской школе
- answer_template: эстонский разговорный шаблон описания с пропусками в квадратных скобках [слово]
- voice_prompt_script: 2-3 ободряющих предложения для озвучки

ДАННЫЕ УЧЕНИКА:
- Имя: {nickname_label}
- Класс: {profile.grade} класс ({tier_label})
- Увлечения (user_interests): {user_interests_str}
- Трендовый возрастной пул (для 30% разнообразия): {fallback_pool_str}

Верни результат СТРОГО в формате JSON."""
